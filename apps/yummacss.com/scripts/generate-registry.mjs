#!/usr/bin/env node

import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join } from "node:path";
import config from "../yumma.config.mjs";
import { componentSlugs, splitId } from "./lib/registry-ids.mjs";

const cwd = process.cwd();
const uiDir = join(cwd, "src/registry/ui");
const contentDir = join(cwd, "src/content/ui");
const outFile = join(cwd, "src/registry/index.ts");

function getIds(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => f.endsWith(".tsx") || f.endsWith(".ts"))
    .map((f) => basename(f, f.endsWith(".tsx") ? ".tsx" : ".ts"));
}

const uiIds = getIds(uiDir);

const uiLines = uiIds
  .map((id) => `  "${id}": () => import("./ui/${id}"),`)
  .join("\n");

const metaDir = join(cwd, "src/registry/meta");
const metaIds = existsSync(metaDir)
  ? readdirSync(metaDir)
      .filter((f) => f.endsWith(".json"))
      .map((f) => basename(f, ".json"))
  : [];

// schemas are imported eagerly, so the Component API renders with the page
const metaName = (id) => `meta_${id.replaceAll("-", "_")}`;
const metaImports = metaIds
  .map((id) => `import ${metaName(id)} from "./meta/${id}.json";`)
  .join("\n");
const metaLines = metaIds.map((id) => `  "${id}": ${metaName(id)},`).join("\n");

const slugs = componentSlugs(contentDir);
const targetLines = uiIds
  .map((id) => {
    const { component, variant } = splitId(id, slugs);
    const kind = variant === "base" ? "component" : "example";

    const install = kind === "block" ? id : component;
    return `  "${id}": { component: "${component}", variant: "${variant}", kind: "${kind}", install: "${install}" },`;
  })
  .join("\n");

// the states, easings and keyframes each component names, so its page can show the config it needs
const { states = {}, easings = {}, keyframes = {} } = config.theme ?? {};
const STATE_ORDER = ["opening", "closing"];
const stateNames = Object.keys(states).sort(
  (a, b) =>
    (STATE_ORDER.indexOf(a) + 1 || 99) - (STATE_ORDER.indexOf(b) + 1 || 99) ||
    a.localeCompare(b),
);
const configLines = uiIds
  .map((id) => {
    const source = readFileSync(join(uiDir, `${id}.tsx`), "utf-8");
    const used = (names, pattern) =>
      names.filter((name) => pattern(name).test(source));
    const s = used(stateNames, (name) => new RegExp(`\\b${name}:`));
    const k = used(
      Object.keys(keyframes),
      (name) => new RegExp(`\\ban:${name}\\b`),
    );
    const e = used(
      Object.keys(easings),
      (name) => new RegExp(`\\b(?:ttf|atf):${name}(?![\\w-])`),
    );
    if (!s.length && !e.length && !k.length) return null;
    const pick = (table, names) =>
      names.length
        ? `{ ${names.map((name) => `${JSON.stringify(name)}: ${JSON.stringify(table[name])}`).join(", ")} }`
        : "{}";
    return `  "${id}": { states: ${pick(states, s)}, easings: ${pick(easings, e)}, keyframes: ${pick(keyframes, k)} },`;
  })
  .filter(Boolean)
  .join("\n");

const output = `/**
 * Generated by scripts/generate-registry.mjs. Do not edit; run
 * \`pnpm generate:registry\` instead.
 */
${metaImports}

export const registry = {
${uiLines}
} as const;

export type RegistryId = keyof typeof registry;
export type RegistryImport = () => Promise<{ default: React.ComponentType<object> }>;

export function getRegistryImport(id: string): RegistryImport | null {
  return (registry as Record<string, RegistryImport>)[id] ?? null;
}

export interface RegistryProp {
  name: string;
  type: "enum" | "boolean" | "string" | "number" | "none";
  typeName?: string;
  values?: string[];
  min?: number;
  max?: number;
  step?: number;
  default?: string | boolean | number;
  example?: unknown;
  exampleIcon?: string;
  optional?: boolean;
  dependsOn?: string;
  handler?: string;
  conflictsWith?: {
    prop: string;
    is?: unknown;
    not?: unknown;
    set?: boolean;
  }[];
  controlled?: boolean;
  description?: string;
}

export interface RegistryMeta {
  summary?: string;
  props: RegistryProp[];
  /** The Example view: the component in use, often several times over. */
  scene: ChildExample[];
}

/** One node of a demo's children: a registry component, a plain element, or text. */
export interface ChildExample {
  component?: string;
  tag?: "div" | "span";
  className?: string;
  props?: Record<string, unknown>;
  children?: string | ChildExample[];
  text?: string;
  /** An icon on its own, as an \`{ "$icon" }\` marker. */
  icon?: unknown;
}

export const registryMeta = {
${metaLines}
} as unknown as Record<string, RegistryMeta>;

export function getRegistryMeta(id: string): RegistryMeta | null {
  return registryMeta[id] ?? null;
}

export interface RegistryTarget {
  component: string;
  variant: string;
  kind: "component" | "block" | "example";
  install: string;
}

export const registryTargets: Record<string, RegistryTarget> = {
${targetLines}
};

export interface RegistryConfig {
  states: Record<string, string>;
  easings: Record<string, string>;
  keyframes: Record<string, string>;
}

export const registryConfig: Record<string, RegistryConfig> = {
${configLines}
};

export function getRegistryTarget(id: string): RegistryTarget {
  return (
    registryTargets[id] ?? {
      component: id,
      variant: "base",
      kind: "component",
      install: id,
    }
  );
}
`;

writeFileSync(outFile, output, "utf-8");
console.log(
  `✓ Registry generated: ${uiIds.length} components, ${metaIds.length} with a prop schema.`,
);
