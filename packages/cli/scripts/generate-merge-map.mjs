/**
 * Writes the prefix-to-properties table `merge` uses, from the utilities
 * `@yummacss/core` defines. Hand-maintaining that table is the cost that makes
 * `tailwind-merge` expensive; core already knows the answer.
 *
 * Run by `pnpm build`. `tests/merge.test.ts` fails if the file is stale.
 */
import { execFileSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import * as core from "@yummacss/core";

const GROUPS = [
	"background",
	"border",
	"boxModel",
	"color",
	"effect",
	"flexbox",
	"font",
	"grid",
	"interactivity",
	"layout",
	"outline",
	"positioning",
	"text",
	"transform",
	"transition",
];

/**
 * 31 prefixes are claimed by more than one utility - `c` is both color and
 * cursor, `p` both padding and position - so a prefix alone cannot say which
 * properties a class sets, and `c-slate-10 c-p` would look like a conflict.
 *
 * The value decides. For each contested prefix the open-ended utility (the
 * palette, the spacing scale) becomes the default and its values are not
 * listed; the keyword utilities are listed by value. 129 keys, not 2,258.
 */
export function buildMap() {
	const byPrefix = new Map();

	for (const group of GROUPS) {
		// biome-ignore lint/performance/noDynamicNamespaceImportAccess: a build script, never bundled
		const utils = core[`${group}Utils`];
		const resolved =
			typeof utils === "function" ? utils({ colors: core.colorTheme }) : utils;

		for (const util of Object.values(resolved ?? {})) {
			if (!util?.prefix || !util?.properties) continue;
			byPrefix.set(util.prefix, [...(byPrefix.get(util.prefix) ?? []), util]);
		}
	}

	const prefixes = new Map();
	const byValue = new Map();

	for (const [prefix, candidates] of [...byPrefix].sort(([a], [b]) =>
		a.localeCompare(b),
	)) {
		const sorted = [...candidates].sort(
			(a, b) =>
				Object.keys(b.values ?? {}).length - Object.keys(a.values ?? {}).length,
		);
		const [fallback, ...rest] = sorted;
		prefixes.set(prefix, [...fallback.properties].sort());

		for (const util of rest) {
			for (const value of Object.keys(util.values ?? {})) {
				const table = byValue.get(prefix) ?? new Map();
				if (!table.has(value)) table.set(value, [...util.properties].sort());
				byValue.set(prefix, table);
			}
		}
	}

	return { prefixes, byValue };
}

export function render({ prefixes, byValue }) {
	const table = (map) =>
		[...map]
			.map(
				([key, value]) => `\t${JSON.stringify(key)}: ${JSON.stringify(value)},`,
			)
			.join("\n");

	const nested = [...byValue]
		.map(
			([prefix, values]) =>
				`\t${JSON.stringify(prefix)}: {\n${[...values]
					.map(
						([v, props]) =>
							`\t\t${JSON.stringify(v)}: ${JSON.stringify(props)},`,
					)
					.join("\n")}\n\t},`,
		)
		.join("\n");

	return `// Generated by scripts/generate-merge-map.mjs. Do not edit.
// Every utility prefix @yummacss/core defines, and the properties it sets.

export const PREFIXES: Record<string, string[]> = {
${table(prefixes)}
};

// Prefixes claimed by more than one utility, resolved by value. Anything not
// listed here falls back to PREFIXES.
export const BY_VALUE: Record<string, Record<string, string[]>> = {
${nested}
};
`;
}

/** Biome formats the repo, so the generator emits what it would have written. */
export function format(source) {
	return execFileSync(
		"pnpm",
		["exec", "biome", "format", "--stdin-file-path=merge-map.ts"],
		{ input: source, encoding: "utf8", cwd: root },
	);
}

const root = join(dirname(fileURLToPath(import.meta.url)), "../../..");
const out = join(
	dirname(fileURLToPath(import.meta.url)),
	"../src/merge-map.ts",
);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
	const map = buildMap();
	writeFileSync(out, format(render(map)));
	const values = [...map.byValue.values()].reduce((n, t) => n + t.size, 0);
	console.log(
		`merge-map.ts: ${map.prefixes.size} prefixes, ${values} disambiguating values`,
	);
}
